import subprocess

EXE = "/workspace/executable"


def invoke(cwd, *args):
    return subprocess.run([EXE, *map(str, args)], cwd=cwd, text=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE)


def project(tmp_path, files):
    for name, content in files.items():
        p = tmp_path / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
    return tmp_path


def test_basic_findings_positions_and_clean_handling(tmp_path):
    project(tmp_path, {"main.go": '''package main
import "os"
func f() error { return nil }
func main() {
    os.Open("x")
    f()
    _ = f()
    e := f()
    _ = e
    println("ok")
}
'''})
    r = invoke(tmp_path, ".")
    assert r.returncode == 1 and r.stderr == ""
    assert r.stdout.splitlines() == [
        'main.go:5:12:\tos.Open("x")',
        'main.go:6:6:\tf()',
    ]


def test_blank_checks_target_position_and_types(tmp_path):
    project(tmp_path, {"main.go": '''package main
func pair() (int, error) { return 0, nil }
func only() error { return nil }
func main() {
    _, _ = pair()
    _ = only()
    _, n := pair()
    _ = n
}
'''})
    r = invoke(tmp_path, "-blank", ".")
    assert r.returncode == 1
    assert r.stdout.splitlines() == [
        'main.go:5:8:\t_, _ = pair()',
        'main.go:6:5:\t_ = only()',
    ]


