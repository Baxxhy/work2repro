def test_ignoretests_and_generated_filters(tmp_path):
    project(tmp_path, {
        "main.go": "package main\nfunc main(){}\n",
        "x_test.go": "package main\nimport \"os\"\nfunc TestX(){os.Open(\"x\")}\n",
        "gen.go": "// Code generated by tool. DO NOT EDIT.\npackage main\nimport \"os\"\nfunc init(){os.Open(\"x\")}\n",
        "ordinary.go": "package main\nimport \"os\"\nfunc other(){os.Open(\"x\")}\n",
    })
    allr = invoke(tmp_path, ".")
    assert allr.returncode == 1 and "x_test.go" in allr.stdout and "gen.go" in allr.stdout
    filtered = invoke(tmp_path, "-ignoretests", "-ignoregenerated", ".")
    assert filtered.returncode == 1 and "ordinary.go" in filtered.stdout
    assert "x_test.go" not in filtered.stdout and "gen.go" not in filtered.stdout


def test_default_exclusions_and_excludeonly(tmp_path):
    project(tmp_path, {"main.go": '''package main
import ("fmt"; "os")
func main() { fmt.Println("x"); os.Open("x") }
'''})
    normal = invoke(tmp_path, ".")
    assert normal.returncode == 1 and "os.Open" in normal.stdout and "fmt.Println" not in normal.stdout
    allr = invoke(tmp_path, "-excludeonly", ".")
    assert allr.returncode == 1 and "fmt.Println" in allr.stdout and "os.Open" in allr.stdout


def test_custom_exclusion_and_ignore_regex(tmp_path):
    project(tmp_path, {"main.go": '''package main
import "os"
func main(){ os.Open("a"); os.OpenFile("b", 0, 0) }
'''})
    ex = tmp_path / "exclude.txt"
    ex.write_text("os.Open\n")
    r = invoke(tmp_path, "-exclude", "exclude.txt", ".")
    assert r.returncode == 1 and "os.Open(" not in r.stdout and "OpenFile" in r.stdout
    ignored = invoke(tmp_path, "-ignore=os:Open$", ".")
    assert ignored.returncode == 1 and "os.Open(" not in ignored.stdout and "OpenFile" in ignored.stdout


def test_ignorepkg_suppresses_calls_into_package(tmp_path):
    project(tmp_path, {"go.mod": "module example.com/m\ngo 1.20\n",
                       "main.go": "package main\nimport \"example.com/m/p\"\nfunc main(){p.F()}\n",
                       "p/p.go": "package p\nimport \"os\"\nfunc F(){os.Open(\"x\")}\n"})
    r = invoke(tmp_path, "-ignorepkg=example.com/m/p", "./...")
    assert r.returncode == 1 and "p/p.go" in r.stdout and "main.go" not in r.stdout


