def test_assertions_checked_separately(tmp_path):
    project(tmp_path, {"main.go": '''package main
func main() {
    var x interface{} = 1
    _ = x.(int)
    _, _ = x.(string)
    switch x.(type) { default: }
}
'''})
    default = invoke(tmp_path, ".")
    assert default.returncode == 0 and default.stdout == ""
    r = invoke(tmp_path, "-asserts", ".")
    assert r.returncode == 1
    assert r.stdout.splitlines() == ['main.go:4:9:\t_ = x.(int)']


def test_deferred_go_and_nested_calls(tmp_path):
    project(tmp_path, {"main.go": '''package main
import "os"
func main() {
    defer os.Open("a")
    go os.Open("b")
    func() { if true { os.Open("c") } }()
}
'''})
    r = invoke(tmp_path, ".")
    assert r.returncode == 1
    lines = r.stdout.splitlines()
    assert len(lines) == 3
    assert lines[0].endswith('\tdefer os.Open("a")')
    assert lines[1].endswith('\tgo os.Open("b")')
    assert lines[2].endswith('\tos.Open("c")')


