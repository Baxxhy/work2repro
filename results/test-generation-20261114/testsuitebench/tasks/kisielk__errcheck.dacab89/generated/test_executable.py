def test_relative_and_absolute_filename_modes(tmp_path):
    project(tmp_path, {"nested/file-name.go": "package p\nimport \"os\"\nfunc F(){os.Open(\"x\")}\n"})
    rel = invoke(tmp_path, "./nested")
    absolute = invoke(tmp_path, "-abspath", "./nested")
    assert rel.returncode == absolute.returncode == 1
    assert rel.stdout.startswith("nested/file-name.go:3:")
    assert absolute.stdout.startswith(str((tmp_path / "nested/file-name.go").resolve()) + ":3:")


