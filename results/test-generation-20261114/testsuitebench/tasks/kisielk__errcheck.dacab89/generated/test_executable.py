def test_flags_stop_at_first_positional_and_help_precedence(tmp_path):
    project(tmp_path, {"main.go": "package main\nfunc main(){}\n"})
    # A help-looking argument after a package pattern is an input, not a flag.
    after_positional = invoke(tmp_path, ".", "--help")
    assert after_positional.returncode == 2
    assert "Usage of" not in after_positional.stderr
    # Help encountered during option parsing wins even over later arguments.
    before_positional = invoke(tmp_path, "-h", "-unknown", ".")
    assert before_positional.returncode == 2
    assert before_positional.stdout == ""
    assert before_positional.stderr.startswith("Usage of /workspace/executable:\n")


